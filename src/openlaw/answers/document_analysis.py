"""The second generation pass: what the person's own document says.

**Why there are two passes at all** (Plan 6 Task 13, ruling A). The security
review of Task 7 found a route the citation validator cannot close: text
inside an uploaded document, once rendered into the generator's prompt, can
steer `Claim.text` -- a false, legal-sounding sentence attached to a
`chunk_id` that really was retrieved this turn. It passes every check in
`openlaw.answers.validate` (which proves "this chunk was retrieved", never
"this sentence is what that chunk says"), renders above a genuine government
URL, and sets `is_answerable=True`.

The containment is structural, not careful. Legal claims are generated by
`openlaw.answers.generate._generate_from_context`, which has no parameter
able to carry a document. Document analysis is this module, which has no
parameter able to carry a corpus chunk and returns a
`openlaw.answers.schema.DocumentDraftAnswer` -- a type with exactly one
field, `document_claims`. There is nowhere for a steered legal claim to
land: not in the prompt that produces them, not in the type this pass
returns, and not in `openlaw.answers.validate.with_document_answer`, which
copies this pass's addendum onto the legal answer and copies nothing else.
Steering a legal claim with document text is therefore impossible rather
than merely unlikely.

**The two prompts never share an id namespace.** This pass is shown the
document's fenced excerpts and no chunk; the legal pass is shown chunks and
no excerpt. `openlaw.answers.prompts.build_turn_messages` narrows replayed
conversation history to the ids actually shown, so the narrowing falls out
for free in both directions: this pass replays earlier document claims and
never an earlier legal claim, and the legal pass replays earlier legal
claims and never a document one.

**What it costs, and when.** One extra generation call, and only on a turn
that actually has excerpts selected -- `analyse_document` returns
immediately, without touching the adapter, for an empty `DocumentContext`,
and `openlaw.answers.generate.generate_turn` skips it entirely for the same
case. The cost was weighed and accepted against the alternative of leaving
an unclosable injection route open on every document turn.

**Nothing here can make a turn answerable, and nothing here is prose.**
There is no `summary` field on this pass's draft -- no document-flavoured
equivalent of `unverified_summary` for unchecked prose to hide in -- and
`is_answerable` is decided solely by the legal pass. A failed, refused or
malformed response yields no document claims rather than raising: the
person's legal answer must not be lost because the reading of their
attachment failed.
"""

from pydantic import BaseModel, ConfigDict

from openlaw.answers.escalation import HallucinationEvent, build_hallucination_events
from openlaw.answers.history import HistoryTurn
from openlaw.answers.models import LLMAdapter, ModelRegistry, ModelRole
from openlaw.answers.prompts import DOCUMENT_SYSTEM_PROMPT, build_document_turn_messages
from openlaw.answers.schema import DOCUMENT_ANSWER_JSON_SCHEMA, DocumentDraftAnswer
from openlaw.answers.validate import (
    EMPTY_VALIDATED_DOCUMENT_ANSWER,
    ValidatedDocumentAnswer,
    rejected_document_claims,
    validate_document_answer,
)
from openlaw.documents.context import DocumentContext
from openlaw.retrieval.context import RetrievalContext

#: Bounds this pass's own output. Lower than
#: `openlaw.answers.generate.MAX_ANSWER_TOKENS` because a document addendum
#: is a handful of short statements about one person's paperwork, never a
#: full legal answer -- and because this pass runs in addition to, not
#: instead of, the legal one.
MAX_DOCUMENT_ANSWER_TOKENS = 1024

#: The corpus context every hallucination event from this pass is logged
#: against: empty, because this pass is shown no chunk. Recording the legal
#: pass's retrieval set here instead would file a document refusal under
#: evidence the document pass never saw.
_NO_CORPUS = RetrievalContext(query="")


class DocumentAnalysis(BaseModel):
    """Everything the document pass produces for one turn.

    Deliberately carries no `crisis`, `footer` or `classifier_failures`:
    those belong to the turn, not to this pass, and this pass must not be
    able to influence any of them. `events` follows the same "build now,
    persist later" split as `openlaw.answers.generate.AnswerResult.events` --
    the caller merges them into the turn's events and one
    `persist_answer_events` call writes both passes' refusals.
    """

    model_config = ConfigDict(frozen=True)

    answer: ValidatedDocumentAnswer = EMPTY_VALIDATED_DOCUMENT_ANSWER
    events: tuple[HallucinationEvent, ...] = ()


_EMPTY_ANALYSIS = DocumentAnalysis()


def analyse_document(
    question: str,
    document_context: DocumentContext,
    adapter: LLMAdapter,
    registry: ModelRegistry,
    history: tuple[HistoryTurn, ...] = (),
) -> DocumentAnalysis:
    """Report what the person's uploaded document says about `question`.

    Has no `RetrievalContext` parameter and no `carried_chunk_ids`
    parameter, by design: this pass cannot be shown the law, so it can never
    be asked to restate it, and the `DocumentDraftAnswer` it parses has no
    field in which a legal claim could travel out of here even if the model
    produced one.

    Spends no model call at all for an empty `document_context` -- a turn
    with no document attached, or one where `select_excerpts` matched
    nothing, costs exactly what it cost before this pass existed.

    Never raises. A refusal, an empty completion or malformed JSON all
    return an empty analysis: the legal answer for this turn has already
    been produced by a pass this one cannot affect, and losing the document
    addendum is strictly better than losing the answer.
    """
    if not document_context.excerpts:
        return _EMPTY_ANALYSIS

    completion = adapter.complete(
        model=registry.for_role(ModelRole.GENERATOR),
        system=DOCUMENT_SYSTEM_PROMPT,
        messages=build_document_turn_messages(question, document_context, history),
        output_schema=DOCUMENT_ANSWER_JSON_SCHEMA,
        max_tokens=MAX_DOCUMENT_ANSWER_TOKENS,
    )
    if completion.stop_reason == "refusal" or not completion.text.strip():
        return _EMPTY_ANALYSIS

    try:
        draft = DocumentDraftAnswer.from_json(completion.text)
    except ValueError:
        return _EMPTY_ANALYSIS

    return DocumentAnalysis(
        answer=validate_document_answer(draft, document_context),
        events=build_hallucination_events(
            question, rejected_document_claims(draft, document_context), _NO_CORPUS
        ),
    )
